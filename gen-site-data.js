// _gen_data.js — regenerate site-data.js from the real folders on disk.
// Usage: node _gen_data.js   (run from the site root)
const fs = require('fs'), path = require('path');
const LABELS = { hotels: '星级酒店', commercial: '高端商业', residential: '精品住宅', urbanism: '城市设计', biddings: '投标方案' };
const imgRe = /\.(webp|png|jpe?g|gif)$/i;
function num(f) { const m = String(f).match(/(\d+)/); return m ? parseInt(m[1], 10) : 0; }

const albums = {};
const ORDER = ['hotels', 'commercial', 'residential', 'urbanism', 'biddings'];
const dirs = fs.readdirSync('images').filter(d => fs.statSync(path.join('images', d)).isDirectory());
for (const dir of [...ORDER.filter(d => dirs.includes(d)), ...dirs.filter(d => !ORDER.includes(d))]) {
  const full = path.join('images', dir);
  const files = fs.readdirSync(full).filter(f => imgRe.test(f));
  files.sort((a, b) => num(a) - num(b) || a.localeCompare(b, 'zh-CN'));
  albums[dir] = {
    label: LABELS[dir] || dir,
    en: dir,
    items: files.map(f => ({ src: dir + '/' + encodeURIComponent(f), n: num(f), file: f }))
  };
}
const aigc = fs.readdirSync('AIGC').filter(f => imgRe.test(f)).map(f => encodeURIComponent(f));
const people = fs.readdirSync('people').filter(f => imgRe.test(f)).map(f => encodeURIComponent(f));

const out = '// Auto-generated by site-data-gen. Do not edit by hand.\n' +
  'window.SITE_DATA = ' + JSON.stringify({ albums, aigc, people }) + ';\n';
fs.writeFileSync('site-data.js', out, 'utf8');
console.log('site-data.js written:',
  Object.keys(albums).map(k => k + ':' + albums[k].items.length).join(', '),
  '| aigc=' + aigc.length, '| people=' + people.length);
